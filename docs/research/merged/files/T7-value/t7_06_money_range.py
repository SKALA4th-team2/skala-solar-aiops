# (14) 오차율 1%p 의 금액: 오차 모양 가정별로 같은 방식으로 환산 (평균 오차율을 전력거래소 평균 5.71% 에 맞춘 가상 예측, 현행 계단)
# 7곳 값은 merged/verify/gap4/indep_out.txt (119~124행)와 solar/agg/out_m2.txt 에서 읽은 값이고, 하동 5곳 값은 out_01_capacity_sens.txt (3c)에서 이번에 다시 계산한 값이다.
KWH_PER_MW = 887346 / 908.17 * 1000   # 7곳 연 발전량 / 용량 (2023-10~2026-02)
ELIG = 0.947                          # 정산 대상 시간대의 발전량 비중
MW_AVG = 5125 / 30
rows = [
 ('7곳, 전날 값 모양, 더하기식 (근거 파일)', 2.494, 8.6, 19.4),
 ('7곳, 전날 값 모양, 같은 비율로 키우는 방식 (근거 파일)', 2.494, 6.8, 12.3),
 ('7곳, 7일 평균 모양, 더하기식 (근거 파일)', 2.196, 15.0, 32.4),
 ('하동 5곳, 전날 값 모양, 더하기식 (재계산)', 2.496, 8.4, 18.6),
 ('하동 5곳, 7일 평균 모양, 더하기식 (재계산)', 2.194, 16.0, 33.0),
 ('하동 5곳, 하루 합계 적중 모양, 더하기식 (재계산, 대상일 실제 합계 사용)', 2.488, 13.2, 29.2),
]
print('MW당 연 발전량 %.0f kWh, 평균 규모 %.1f MW' % (KWH_PER_MW, MW_AVG))
for nm, unit, d1, d2 in rows:
    base = unit * ELIG * KWH_PER_MW
    print(' %s: 단가 %.3f원, MW당 연 %.1f만 원, %.0fMW 연 %.2f억 원 | 1%%p %.1f%% = MW당 %.1f만 원, %.0fMW %.0f만 원 | 2%%p %.1f%% = %.0fMW %.0f만 원'
          % (nm, unit, base / 1e4, MW_AVG, base * MW_AVG / 1e8, d1, base * d1 / 100 / 1e4, MW_AVG, base * MW_AVG * d1 / 100 / 1e4, d2, MW_AVG, base * MW_AVG * d2 / 100 / 1e4))
print(' 업체 예상 기준선(해줌, 1MW 연 330만 원)으로 바꾸면: %.0fMW 연 %.2f억 원, 1%%p(8.6%%) %.0f만 원' % (MW_AVG, 330 * MW_AVG / 1e4, 330 * MW_AVG * 0.086))
print(' 계단 하락을 문헌의 연 저하율로 환산: 8.5%% / 0.9%% = %.1f년, 8.5%% / 0.5%% = %.1f년' % (8.5 / 0.9, 8.5 / 0.5))
print(' 정산금 상한과 같아지는 판매 단가: 272,642원 / 6,596kWh = %.1f원/kWh' % (272642 / 6596))
