/**
 * 작성자: Git 이력 참조
 * 작성목적: 독립 SOLAR OPS 디자인 원본을 공유 가능한 단일 HTML로 패키징한다.
 * 작성일: 2026-10-07
 * 입력: docs/design/solar-ops-v01/{index.html,styles.css,app.js}
 * 출력: 같은 폴더의 solar-ops-preview.html. API나 원본 데이터를 건드리지 않는다.
 */
import { readFile, writeFile } from "node:fs/promises";

const previewFolder = new URL("../../docs/design/solar-ops-v01/", import.meta.url);
const [markup, stylesheet, core, script, operations, serverDashboard] = await Promise.all(
  ["index.html", "styles.css", "dashboard-core.js", "app.js", "operations.js", "server-dashboard.js"].map((filename) => readFile(new URL(filename, previewFolder), "utf8"))
);
const standalone = markup
  .replace('<link rel="stylesheet" href="styles.css">', () => `<style>\n${stylesheet}\n</style>`)
  .replace('  <script src="dashboard-core.js" defer></script>\n', "")
  .replace('  <script src="app.js" defer></script>\n', "")
  .replace('  <script src="operations.js" defer></script>\n', "")
  .replace('  <script src="server-dashboard.js" defer></script>\n', "")
  .replace("</body>", () => `<script>\n${core}\n${script}\n${operations}\n${serverDashboard}\n</script>\n</body>`)
  .replace("<!doctype html>", "<!doctype html>\n<!-- Generated by tools/design/build-preview.mjs. Edit index.html, styles.css and app.js, then rebuild. -->");
await writeFile(new URL("solar-ops-preview.html", previewFolder), standalone, "utf8");
console.log("Built docs/design/solar-ops-v01/solar-ops-preview.html");
