import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath, pathToFileURL } from "node:url";

export const REPLAY_DATE = "2025-06-04";
export const SOURCE_URL = new URL("../../datasets/hadong_upload_forecast_jma.csv", import.meta.url);
const appUrl = new URL("../../docs/design/solar-ops-v01/app.js", import.meta.url);
const blockPattern = /\/\/ BEGIN chart-data\n[\s\S]*?\/\/ END chart-data/;

export function shiftDate(isoDate, offset) {
  const day = new Date(`${isoDate}T00:00:00Z`);
  day.setUTCDate(day.getUTCDate() + offset);
  return day.toISOString().slice(0, 10);
}

export function parseSource(csv) {
  const [header, ...lines] = csv.replace(/^\uFEFF/, "").trim().split(/\r?\n/);
  if (header !== "Date,Close,Volume,Stop") throw new Error("Unexpected CSV header");
  const rows = new Map();
  for (const line of lines) {
    const [date, measuredText, forecastText, stop, ...extra] = line.split(",");
    const measured = Number(measuredText);
    const nextDayForecast = Number(forecastText);
    if (!/^\d{4}-\d{2}-\d{2}$/.test(date) || shiftDate(date, 0) !== date || rows.has(date)) {
      throw new Error(`Invalid or duplicate date: ${date}`);
    }
    if (extra.length || stop === undefined || measuredText === "" || forecastText === "" ||
        !Number.isFinite(measured) || !Number.isFinite(nextDayForecast) || measured < 0 || nextDayForecast < 0) {
      throw new Error(`Invalid generation or irradiance: ${date}`);
    }
    rows.set(date, { measured, nextDayForecast });
  }
  return rows;
}

function requiredRow(rows, date) {
  if (!rows.has(date)) throw new Error(`Missing source date: ${date}`);
  return rows.get(date);
}

export function forecastForDate(rows, date) {
  return requiredRow(rows, shiftDate(date, -1)).nextDayForecast;
}

export function predictForDate(rows, date) {
  const previousDays = Array.from({ length: 7 }, (_, index) => shiftDate(date, index - 7));
  const measuredSum = previousDays.reduce((sum, day) => sum + requiredRow(rows, day).measured, 0);
  const forecastSum = previousDays.reduce((sum, day) => sum + forecastForDate(rows, day), 0);
  if (forecastSum <= 0) throw new Error(`Zero forecast denominator: ${date}`);
  return measuredSum / forecastSum * forecastForDate(rows, date);
}

export function buildChartData(rows, replayDate = REPLAY_DATE) {
  const records = Array.from({ length: 90 }, (_, index) => {
    const date = shiftDate(replayDate, index - 89);
    return {
      date,
      measured: requiredRow(rows, date).measured,
      predicted: predictForDate(rows, date),
      forecastIrradiance: forecastForDate(rows, date)
    };
  });
  const rmseByPeriod = Object.fromEntries([7, 30, 90].map((period) => {
    const errors = records.slice(-period).map(({ measured, predicted }) => (predicted - measured) ** 2);
    return [period, Math.sqrt(errors.reduce((sum, squaredError) => sum + squaredError, 0) / period)];
  }));
  const tomorrowDate = shiftDate(replayDate, 1);
  return {
    records,
    summary: {
      replayDate,
      tomorrow: { date: tomorrowDate, predicted: predictForDate(rows, tomorrowDate), forecastIrradiance: forecastForDate(rows, tomorrowDate) },
      recentWeekMean: records.slice(-7).reduce((sum, record) => sum + record.measured, 0) / 7,
      rmseByPeriod
    }
  };
}

export function renderDataBlock({ records, summary }) {
  // Full precision keeps the plotted line, exported CSV and RMSE on the same values.
  return [
    "// BEGIN chart-data",
    "// Generated by tools/design/generate-chart-data.mjs; do not edit values by hand.",
    "// measured: kWh/day; predicted: seven-day ratio baseline (not LSTM); forecastIrradiance: MJ/m².",
    `const chartSummary = ${JSON.stringify(summary, null, 2)};`,
    "const dailyRecords = [",
    records.map((record) => `  ${JSON.stringify(record)}`).join(",\n"),
    "];",
    "// END chart-data"
  ].join("\n");
}

export function rewriteDataBlock(script, block) {
  if ((script.match(/\/\/ BEGIN chart-data/g) || []).length !== 1 ||
      (script.match(/\/\/ END chart-data/g) || []).length !== 1 || !blockPattern.test(script)) {
    throw new Error("Expected exactly one chart-data block");
  }
  return script.replace(blockPattern, () => block);
}

async function main() {
  const rows = parseSource(await readFile(SOURCE_URL, "utf8"));
  const chartData = buildChartData(rows);
  const original = await readFile(appUrl, "utf8");
  const generated = rewriteDataBlock(original, renderDataBlock(chartData));
  if (process.argv.includes("--check")) {
    if (original !== generated) throw new Error("Chart data is stale; run generate-chart-data.mjs");
  } else if (generated !== original) {
    await writeFile(appUrl, generated, "utf8");
  }
  console.log(JSON.stringify({ mode: process.argv.includes("--check") ? "check" : "generate", ...chartData.summary }, null, 2));
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch((error) => { console.error(`${fileURLToPath(appUrl)}: ${error.message}`); process.exitCode = 1; });
}
